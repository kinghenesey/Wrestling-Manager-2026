// Helper to get orgs available to a manager by reputation
export function getAvailableOrgs(reputation: string) {
  const tierMap: Record<string, string[]> = {
    unknown:   ['local', 'underground'],
    regional:  ['local', 'indie', 'underground'],
    respected: ['local', 'indie', 'regional', 'underground'],
    notable:   ['local', 'indie', 'regional', 'major', 'underground'],
    elite:     ['local', 'indie', 'regional', 'major', 'elite', 'underground'],
    legendary: ['local', 'indie', 'regional', 'major', 'elite', 'underground'],
  }
  const allowed = tierMap[reputation] ?? ['local']
  return ORGANIZATIONS.filter(o => allowed.includes(o.tier))
}